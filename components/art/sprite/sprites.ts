/** Diagonal chain-link mesh between a top rail and posts. */
const meshRows = (): string[] => {
	const out = ["................", "................", "RRRRRRRRRRRRRRRR"];
	for (let y = 0; y < 10; y++) {
		let r = "";
		for (let x = 0; x < 16; x++) r += x === 1 || x === 14 ? "P" : (x + y) % 4 === 0 || (x - y + 40) % 4 === 0 ? "m" : ".";
		out.push(r);
	}
	out.push("rRRRRRRRRRRRRRRr".replace(/R/g, "m").replace(/r/g, "P"));
	out.push(".P............P.");
	return out;
};

