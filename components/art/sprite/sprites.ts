/**
 * 16×16 pixel sprites for the scene view. Each row is 16 characters; "." is
 * transparent and every other character is a key into the sprite's palette.
 * Palette keys H/C/c/S on creatures are filled per character (hair, cloth, skin).
 */

export interface Sprite {
	rows: string[];
	pal: Record<string, string>;
}

const E = "................";
const sp = (pal: Record<string, string>, ...rows: string[]): Sprite => {
	while (rows.length < 16) rows.push(E);
	return { pal, rows };
};

