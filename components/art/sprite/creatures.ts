/** Aliases for keys iconKeyFor can return that aren't drawn separately. */
const ALIAS: Record<string, string> = {
	pc: "humanoid",
	pc_fighter: "knight",
	pc_rogue: "archer",
	pc_wizard: "mage",
};

/** The sprite for a creature's token hint (SRD `tokenHint`, a name, a kind). */
export function creatureSprite(hint: string | undefined, kind: "pc" | "monster" | "npc"): Sprite {
	const h = (hint ?? "").toLowerCase();
	const key = /insect|beetle|wasp|centipede/.test(h) ? "spider" : iconKeyFor(hint, kind);
	const k = ALIAS[key] ?? key;
	return CREATURE_SPRITES[k] ?? CREATURE_SPRITES[kind === "monster" ? "monstrosity" : "humanoid"];
}
